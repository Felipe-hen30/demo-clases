package com.afbh.demo.clases.service;

public class Bicicleta {
	private String tipo;
	private int ruedas;
	private double numeroRin;
 
	public void setTipo(String paramteroTipo) {
		this.tipo = parametroTipo;
		
		
	}
	public String getTipo() {
		return this.tipo;
		
	}
	public void setRuedas(int parametroRuedas) {
		this.ruedas = paramteroRuedas;
		
	}
	public int getRuedas() {
		return this.ruedas;
		
	}
	public void setNumeroRin(double paramteroNumeroRin) {
		this.numeroRin = paramteroNumeroRin;
		
	}
	public double getNumeroRin() {
		return this.numeroRin;
		
	}
}
